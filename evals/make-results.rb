# Turns the JSON of a full `claude plugin eval --json` run into evals/RESULTS.md, so every
# number in the README can be checked against the per-case table it comes from.
#
# Usage: RUN_NOTE="Agent: … · judge: …" ruby evals/make-results.rb <run.json> [<re-run.json> ...] > evals/RESULTS.md
# Later files replace cases of the same name (a re-run after a grader fix).
# Cases are grouped by folder: evals/held-out-independent/ (written by an agent that never
# saw the skill), evals/held-out/ (written before tuning), and the rest (used for tuning).
require "json"
require "yaml"

abort "usage: ruby evals/make-results.rb <run.json> [<re-run.json> ...]" if ARGV.empty?
evals = File.expand_path(__dir__)
runs = ARGV.map { |f| JSON.parse(File.read(f)) }
cases = {}
rerun = []
runs.each_with_index do |d, i|
  d["cases"].each do |c|
    rerun << c["name"] if i.positive?
    cases[c["name"]] = c
  end
end

name_of = lambda do |dir|
  f = File.join(dir, "case.yaml")
  File.exist?(f) ? YAML.safe_load(File.read(f))["name"] : File.basename(dir)
end
group = {}
Dir[File.join(evals, "held-out", "*/")].each { |d| group[name_of.(d)] = "held-out" }
Dir[File.join(evals, "held-out-independent", "*/")].each { |d| group[name_of.(d)] = "independent" }

mean = ->(xs) { xs.empty? ? nil : xs.sum.to_f / xs.size }
arm = ->(c, a) { c["arms"][a] || [] }
score = ->(c, a) { mean.(arm.(c, a).map { |r| r["score"].to_f }) }
turns = ->(c, a) { mean.(arm.(c, a).map { |r| r["turns"].to_f }) }
cost = ->(c, a) { arm.(c, a).sum { |r| r["costUsd"].to_f } }
fmt = ->(x) { x.nil? ? "–" : format("%.2f", x) }

first = runs.first
out = []
out << "# Eval results"
out << ""
out << "Generated by `evals/make-results.rb` from a `claude plugin eval` run. Every case runs with and without the skill; the score is the share of graders passed, averaged over the runs."
out << ""
out << "- Run started: #{first["startedAt"]} · Claude Code #{first["claudeVersion"]}"
out << "- #{ENV["RUN_NOTE"]}" if ENV["RUN_NOTE"] # e.g. which model did the work and which judged it
out << "- Runs per case: #{cases.values.map { |c| arm.(c, "with").size }.max}"
out << "- Re-run after a fix, with the same settings (these replace the main run): #{rerun.uniq.sort.join(", ")}" unless rerun.empty?
out << ""
out << "| Group | Cases | Without the skill | With the skill |"
out << "|---|:---:|:---:|:---:|"
[["Independent held-out (written by an agent that never saw the skill)", "independent"],
 ["Held-out (written before tuning, never used to change the skill)", "held-out"],
 ["Tuned (used while building the skill)", nil]].each do |label, g|
  set = cases.values.select { |c| group[c["name"]] == g }
  next if set.empty?
  out << "| #{label} | #{set.size} | #{fmt.(mean.(set.map { |c| score.(c, "without") }.compact))} | #{fmt.(mean.(set.map { |c| score.(c, "with") }.compact))} |"
end
all = cases.values
out << "| **All** | #{all.size} | #{fmt.(mean.(all.map { |c| score.(c, "without") }.compact))} | #{fmt.(mean.(all.map { |c| score.(c, "with") }.compact))} |"
out << ""
tw = mean.(all.map { |c| turns.(c, "with") }.compact)
to = mean.(all.map { |c| turns.(c, "without") }.compact)
cw = all.sum { |c| cost.(c, "with") }
co = all.sum { |c| cost.(c, "without") }
out << "Cost: #{format("%.1f", tw)} turns per run with the skill, #{format("%.1f", to)} without; #{format("%.2f", co.zero? ? 0 : cw / co)}× the spend."
out << ""
out << "| Case | Group | Without | With | Turns without → with |"
out << "|---|---|:---:|:---:|:---:|"
all.sort_by { |c| [group[c["name"]] || "tuned", c["name"]] }.each do |c|
  out << "| #{c["name"]} | #{group[c["name"]] || "tuned"} | #{fmt.(score.(c, "without"))} | #{fmt.(score.(c, "with"))} | #{format("%.1f", turns.(c, "without") || 0)} → #{format("%.1f", turns.(c, "with") || 0)} |"
end
puts out.join("\n")
